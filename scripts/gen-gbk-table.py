"""Generate miniprogram/utils/gbk-table.js from Python's GB18030 codec.

The table covers all two-byte GBK/GB18030 sequences:
lead byte 0x81-0xFE, trail byte 0x40-0x7E or 0x80-0xFE (190 values).
Index = (lead - 0x81) * 190 + trailIndex. Unmapped sequences become U+FFFD.

Usage: python3 scripts/gen-gbk-table.py
"""
import json
import os

chars = []
for lead in range(0x81, 0xFF):
    for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
        try:
            ch = bytes([lead, trail]).decode("gb18030")
        except UnicodeDecodeError:
            ch = "\ufffd"
        if len(ch) != 1:
            ch = "\ufffd"
        chars.append(ch)

literal = json.dumps("".join(chars), ensure_ascii=False)
# U+2028/U+2029 are line terminators in older JS engines.
literal = literal.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")

out = os.path.join(os.path.dirname(__file__), "..", "miniprogram", "utils", "gbk-table.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/gen-gbk-table.py. Do not edit.\n")
    f.write("// Two-byte GBK/GB18030 -> Unicode, 126 lead bytes x 190 trail bytes.\n")
    f.write("module.exports = " + literal + "\n")
print("entries:", len(chars))
